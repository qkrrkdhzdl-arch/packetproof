/*
 * i18n.js — every string the app shows, in English and Korean.
 *
 * Findings are produced as codes plus parameters (never as finished
 * sentences), so the same packet can be read in either language and the
 * wording can change without touching the checks.
 */

export const LANGS = ['en', 'ko'];

export function pickLang(saved) {
  if (saved === 'en' || saved === 'ko') return saved;
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'en';
  return nav.toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

